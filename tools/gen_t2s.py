#!/usr/bin/env python3
"""Regenerate tools/t2s_map.py (Traditional -> Simplified character map).

Only needed when Chinese text in data.py / build.py changes. Requires OpenCC:
    pip install opencc-python-reimplemented
    python3 tools/gen_t2s.py
build.py itself has no dependencies.
"""
import os
import opencc

HERE = os.path.dirname(os.path.abspath(__file__))
cc = opencc.OpenCC("t2s")
chars = set()
for name in ("data_immd.py", "data_travel.py", "data_info.py", "data_esvc.py", "build.py"):
    with open(os.path.join(HERE, name), encoding="utf-8") as f:
        chars |= {c for c in f.read() if "一" <= c <= "鿿"}
m = {c: cc.convert(c) for c in sorted(chars) if cc.convert(c) != c}
lines = ["# -*- coding: utf-8 -*-", "# Generated by tools/gen_t2s.py - do not edit by hand.", "T2S = {"]
row = []
for i, (k, v) in enumerate(m.items()):
    row.append('"%s": "%s",' % (k, v))
    if len(row) == 8:
        lines.append("    " + " ".join(row)); row = []
if row:
    lines.append("    " + " ".join(row))
lines += [
    "}",
    "",
    "# Phrase-level overrides for HK-style Traditional terms (applied before the character map).",
    "PHRASES = [",
    '    ("流動通訊", "移动通信"), ("流動應用程式", "移动应用程序"), ("開放數據入門網站", "开放数据门户网站"),',
    '    ("個人稅務入門網站", "个人税务门户网站"), ("商業稅務入門網站", "商业税务门户网站"),',
    '    ("入門網站", "门户网站"), ("資訊保安", "信息安全"), ("資訊", "信息"), ("數碼", "数字"),',
    '    ("通訊", "通信"), ("軟件", "软件"), ("互聯網", "互联网"), ("短訊", "短信"), ("視乎", "视乎"),',
    '    ("進階搜尋", "高级搜索"), ("搜尋", "搜索"), ("流動電話", "手机"), ("網頁", "网页"), ("連結", "链接"),',
    "]",
    "",
]
with open(os.path.join(HERE, "t2s_map.py"), "w", encoding="utf-8") as f:
    f.write("\n".join(lines))
print(len(m), "chars mapped")
